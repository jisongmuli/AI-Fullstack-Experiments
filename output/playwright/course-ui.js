async (page) => {
  const checks=[],errors=[];
  const check=(value,name)=>{if(!value)throw Error(name);checks.push({name,passed:true})};
  page.on('pageerror',error=>errors.push(error.message));
  try{
    await page.setViewportSize({width:1440,height:1000});
    await page.goto('http://127.0.0.1:8006/?v=course20261027#course');
    await page.reload();
    await page.locator('.course-stage').first().waitFor();
    check(await page.locator('.nav-item').count()===6,'All six workflows are reachable');
    check(await page.locator('.course-stage').count()===5,'All five course stages appear');
    check((await page.locator('#course-stages').textContent()).match(/已就绪/g).length===5,'Each course stage has completed records');
    check((await page.locator('#course-measurements').textContent()).includes('98.50%'),'Course metrics display actual heldout measurements');
    const [download]=await Promise.all([page.waitForEvent('download'),page.locator('#course-download').click()]);
    await download.saveAs('E:/AIGC_latest_20261011/output/playwright/course-downloads/experiment-records.json');
    check(download.suggestedFilename().endsWith('.json'),'Full course records can be downloaded');
    await page.screenshot({path:'output/playwright/course-desktop.png',fullPage:true});
    await page.locator('#course-try-text').click();
    await page.waitForFunction(()=>document.querySelector('#text-input').value.length>80);
    check(await page.locator('#model-profile').inputValue()==='course-optimized','Course example selects the optimized deployment');
    const [optimized]=await Promise.all([page.waitForResponse(r=>r.url().endsWith('/api/course/text/detect')&&r.request().method()==='POST'),page.locator('#detect-text').click()]);
    check((await optimized.json()).model_version==='course-text-optimized-20261027','Text page really invokes the optimized trained model');
    await page.locator('#detect-text').isEnabled();
    await page.locator('#model-profile').selectOption('course-trained');
    const [trained]=await Promise.all([page.waitForResponse(r=>r.url().endsWith('/api/course/text/detect')&&r.request().method()==='POST'),page.locator('#detect-text').click()]);
    check((await trained.json()).model_version==='course-text-trained-20261027','The experimental baseline is separately executable');
    await page.locator('.nav-item[data-view="course"]').click();
    await page.locator('#course-try-image').click();
    await page.waitForFunction(()=>state.imageReady);
    const [image]=await Promise.all([page.waitForResponse(r=>r.url().includes('/api/course/image/detect')&&r.request().method()==='POST'),page.locator('#detect-image').click()]);
    check((await image.json()).model_version==='course-image-optimized-20261027','Image page calls the physically pruned exported model');
    await page.locator('#model-profile').selectOption('advanced');
    await page.locator('#image-input').setInputFiles('E:/AIGC_latest_20261011/output/playwright/resolution-fixtures/3840x2160-RGB.png');
    await page.waitForFunction(()=>state.imageReady&&document.querySelector('#image-preview').naturalWidth===3840);
    const [advanced]=await Promise.all([page.waitForResponse(r=>r.url().endsWith('/api/image/detect')&&r.request().method()==='POST'),page.locator('#detect-image').click()]);
    const advancedResult=await advanced.json();
    check(advancedResult.input_size.join('x')==='3840x2160'&&advancedResult.model_version.startsWith('dear_'),'The advanced 4K path is preserved');
    await page.setViewportSize({width:390,height:844});
    await page.locator('.nav-item[data-view="course"]').click();
    check(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'The course page fits a 390px viewport');
    await page.screenshot({path:'output/playwright/course-mobile.png',fullPage:true});
    await page.locator('#course-open-agent').click();
    await page.locator('#agent-instruction').fill('看看这篇正文的生成信号');
    const example=await (await page.request.get('http://127.0.0.1:8006/api/course/example/text')).json();
    await page.locator('#agent-text').fill(example.text.slice(0,350));
    await page.locator('#agent-profile').selectOption('course');
    const [agentResponse]=await Promise.all([page.waitForResponse(r=>r.url().endsWith('/api/agent/run')&&r.request().method()==='POST',{timeout:180000}),page.locator('#agent-submit').click()]);
    const answer=await agentResponse.json();
    check(agentResponse.status()===200&&answer.planner.tools.join(',')==='text_detection','The real fine-tuned local LLM selects text detection');
    check(answer.tool_calls[0].path==='/api/course/text/detect'&&answer.tool_calls[0].http_status===200,'The assistant executes the course API');
    check(answer.answer_source==='local_llm','The final explanation is generated by the local LLM');
    await page.locator('#agent-result .agent-tool').waitFor();
    check((await page.locator('#agent-result').textContent()).includes('/api/course/text/detect'),'The interface displays API tool traces');
    check(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'The assistant and tool results fit a 390px viewport');
    await page.screenshot({path:'output/playwright/course-agent-mobile.png',fullPage:true});
    await page.locator('#agent-clear').click();
    check(await page.locator('#agent-text').inputValue()===''&&await page.locator('#agent-instruction').inputValue()==='','Conversation reset clears input and attachments');
    check(errors.length===0,'No uncaught errors in the course and Agent workflows');
    return JSON.stringify({status:'passed',checks,errors,actual_models:true});
  }catch(error){return JSON.stringify({status:'failed',checks,errors,error:String(error)})}
}
