async (page) => {
  const checks=[], errors=[];
  page.on('pageerror', error => errors.push(error.message));
  const check=(name,passed)=>{if(!passed)throw new Error(name);checks.push({name,passed});};
  const original='The team reviewed 20 samples in order to check whether the results were consistent across the two groups.';
  await page.goto('http://127.0.0.1:8002/?v=bugs20261025#text');
  await page.reload();
  await page.setViewportSize({width:1280,height:900});
  await page.locator('#text-input').fill(original);
  await page.locator('#detect-text').click();
  await page.locator('#text-result .result-header').waitFor();
  await page.locator('#text-input').fill(original+' This version contains new text.');
  check('Changing completed text invalidates its previous result', await page.locator('#text-result .result-header').count()===0);
  check('Updated text shows a request to analyze again', await page.locator('#text-result').getByText('输入已更新',{exact:true}).isVisible());
  await page.screenshot({path:'output/playwright/bug-text-invalidated.png',fullPage:true});
  await page.locator('#detect-text').click();
  await page.locator('#text-result .result-header').waitFor();
  check('Reanalysis renders the current text', (await page.locator('#text-result .document-reader').innerText()).includes('This version contains new text.'));

  await page.getByRole('button',{name:'可信编辑',exact:true}).click();
  await page.locator('#edit-input').fill(original);
  await page.locator('#run-edit').click();
  await page.locator('#copy-edit').waitFor();
  await page.evaluate(()=>Object.defineProperty(navigator.clipboard,'writeText',{configurable:true,value:()=>Promise.reject(new DOMException('Clipboard denied in regression fixture','NotAllowedError'))}));
  await page.locator('#copy-edit').click();
  await page.getByRole('button',{name:'复制失败，请手动复制',exact:true}).waitFor();
  check('Clipboard denial is handled without removing the suggestion', await page.locator('#edit-output').isVisible());
  check('Clipboard denial produces no uncaught browser exception', errors.length===0);
  await page.locator('#edit-input').fill(original+' The original text was changed.');
  check('Changed editor input removes the old copy and apply actions', await page.locator('#copy-edit').count()===0 && await page.locator('#use-edit').count()===0);
  await page.locator('#run-edit').click();
  await page.locator('#edit-output').waitFor();
  const edited=await page.locator('#edit-output').innerText();
  await page.locator('#use-edit').click();
  check('Applying an edit updates the input and invalidates the old comparison', await page.locator('#edit-input').inputValue()===edited && await page.locator('#use-edit').count()===0);
  await page.route('**/api/text/edit/llm-preview',route=>route.fulfill({json:{status:'review_candidate',candidate:original}}));
  await page.locator('#run-llm-edit').click();
  await page.locator('#edit-result .edit-output').waitFor();
  await page.locator('#edit-input').fill(original+' Changed after the LLM result.');
  check('Changing input also invalidates a completed LLM preview', await page.locator('#edit-result .edit-output').count()===0);
  await page.unroute('**/api/text/edit/llm-preview');

  await page.getByRole('button',{name:'Agent 助手',exact:true}).click();
  const documentInput=page.locator('#agent-document-input');
  await documentInput.setInputFiles({name:'previous.txt',mimeType:'text/plain',buffer:Buffer.from(original)});
  check('A valid document enables Agent submission', await page.locator('#agent-form button').isEnabled());
  await documentInput.setInputFiles({name:'rejected.exe',mimeType:'application/octet-stream',buffer:Buffer.from('invalid')});
  check('An unsupported replacement clears the previous document', await page.locator('#agent-document-name').isHidden() && await page.locator('#agent-form button').isDisabled());
  check('The rejected file input is reset', await documentInput.evaluate(element=>element.files.length)===0);
  await documentInput.setInputFiles({name:'previous.txt',mimeType:'text/plain',buffer:Buffer.from(original)});
  await documentInput.setInputFiles({name:'empty.txt',mimeType:'text/plain',buffer:Buffer.alloc(0)});
  await page.getByText('文档为空，请重新选择。',{exact:true}).waitFor();
  check('An empty replacement cannot submit the old document', await page.locator('#agent-document-name').isHidden() && await page.locator('#agent-form button').isDisabled());
  await page.locator('#agent-text-file').setInputFiles({name:'unicode.txt',mimeType:'text/plain',buffer:Buffer.from('😀'.repeat(6000))});
  await page.waitForFunction(()=>Array.from(document.getElementById('agent-input').value).length===6000);
  check('A valid 6000-codepoint import is accepted', await page.locator('#agent-form button').isEnabled());
  await page.locator('#agent-text-file').setInputFiles({name:'boundary.txt',mimeType:'text/plain',buffer:Buffer.from('😀'.repeat(10000))});
  await page.waitForFunction(()=>Array.from(document.getElementById('agent-input').value).length===10000);
  check('The exact 10000-codepoint import boundary is accepted', await page.locator('#agent-form button').isEnabled());
  await page.locator('#agent-text-file').setInputFiles({name:'oversize.txt',mimeType:'text/plain',buffer:Buffer.from('😀'.repeat(10001))});
  await page.getByText('文本超过 10,000 字符，请缩短后重试。',{exact:true}).waitFor();
  check('Over-limit imports are rejected while preserving visible input', await page.locator('#agent-input').evaluate(element=>Array.from(element.value).length)===10000);
  await page.locator('#agent-input').fill('a'.repeat(159)+'😀'+'b'.repeat(5));
  await page.route('**/api/agent/upload',route=>route.fulfill({json:{findings:{},tool_calls:[],decision:'no_input'}}));
  await page.locator('#agent-form button').click();
  await page.waitForFunction(()=>!document.querySelector('#agent-form button').disabled);
  check('Agent message previews do not split an emoji', (await page.locator('.message.user .bubble').last().innerText()).endsWith('😀…'));
  await page.unroute('**/api/agent/upload');

  await page.getByRole('button',{name:'图像检测',exact:true}).click();
  const image=await(await page.request.get('http://127.0.0.1:8002/static/assets/sample-fake.png')).body();
  const real=page.getByRole('button',{name:'真实类样本缩略图 真实类样本',exact:true});
  const fake=page.getByRole('button',{name:'生成类样本缩略图 生成类样本',exact:true});
  let arrive,release;
  let ready=new Promise(resolve=>arrive=resolve),gate=new Promise(resolve=>release=resolve);
  await page.route('**/static/assets/sample-real.png',async route=>{arrive();await gate;await route.fulfill({body:image,contentType:'image/png'});});
  let response=page.waitForResponse(item=>item.url().endsWith('/static/assets/sample-real.png'));
  try{await real.click();await ready;await page.locator('#image-input').setInputFiles({name:'manual.png',mimeType:'image/png',buffer:image});}finally{release();}
  await response;await page.evaluate(()=>new Promise(requestAnimationFrame));
  check('A delayed sample cannot replace a newer manual image', await page.locator('#file-name').innerText()==='manual.png');
  await page.unroute('**/static/assets/sample-real.png');
  ready=new Promise(resolve=>arrive=resolve);gate=new Promise(resolve=>release=resolve);
  await page.route('**/static/assets/sample-real.png',async route=>{arrive();await gate;await route.fulfill({body:image,contentType:'image/png'});});
  response=page.waitForResponse(item=>item.url().endsWith('/static/assets/sample-real.png'));
  try{await real.click();await ready;await page.locator('#clear-image').click();}finally{release();}
  await response;await page.evaluate(()=>new Promise(requestAnimationFrame));
  check('Clearing the image cancels an earlier sample selection', await page.locator('#file-meta').isHidden() && await page.locator('#detect-image').isDisabled());
  await page.unroute('**/static/assets/sample-real.png');
  await page.route('**/static/assets/sample-fake.png',route=>route.fulfill({status:404,body:'missing sample'}));
  await fake.click();
  await page.getByText('示例图片加载失败（404），请重新选择图片。',{exact:true}).waitFor();
  check('A failed sample download is reported instead of marked ready', await page.locator('#detect-image').isDisabled() && await page.locator('#file-meta').isHidden());
  await page.screenshot({path:'output/playwright/bug-sample-error.png',fullPage:true});
  await page.unroute('**/static/assets/sample-fake.png');
  let releaseFirst,firstArrive;
  const firstReady=new Promise(resolve=>firstArrive=resolve),firstGate=new Promise(resolve=>releaseFirst=resolve);
  await page.route('**/static/assets/sample-real.png',async route=>{firstArrive();await firstGate;await route.fulfill({body:image,contentType:'image/png'});});
  response=page.waitForResponse(item=>item.url().endsWith('/static/assets/sample-real.png'));
  try{await real.click();await firstReady;await fake.click();await page.getByText('cifake-fake-sample.png',{exact:true}).waitFor();}finally{releaseFirst();}
  await response;await page.evaluate(()=>new Promise(requestAnimationFrame));
  check('The latest sample selection wins when downloads finish out of order', await page.locator('#file-name').innerText()==='cifake-fake-sample.png');
  await page.unroute('**/static/assets/sample-real.png');
  await page.locator('#detect-image').click();
  await page.locator('#image-result .result-header').waitFor();
  check('The real image model still analyzes the selected file', await page.locator('#detect-image').isEnabled());
  check('No uncaught browser errors in the repaired flows', errors.length===0);
  return {status:'passed',checks,errors};
}
